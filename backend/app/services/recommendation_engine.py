import datetime
from typing import List, Dict, Any, Optional, Tuple
from app.models.subscription import Subscription
from app.models.transaction import Transaction
from app.models.recommendation import Recommendation
from app.models.business import BusinessProfile
from app.schemas.recommendation import (
    PurchaseSimulationRequest,
    PurchaseSimulationResponse,
    AnnualVsMonthlyComparison,
    MonthProjectionPoint,
)
from app.services.subscription_analyzer import SubscriptionExpenseAnalyzer
from app.services.forecast_engine import ForecastEngine


class RecommendationEngine:
    """
    Intelligent Calendar-Aware AI Recommendation & Purchase Simulation Engine for PayPal SubWise AI.

    Stage 4 Architectural Principles:
    1. Deterministic & Grounded: Calculates financial metrics strictly using completed PayPal transactions,
       confirmed subscription obligations, calendar renewal dates, and forward cash-flow forecasts.
    2. AI Transparency: Recommendations and affordability verdicts are generated by deterministic rules
       and verified cash projections. Machine learning or LLM labels are not falsely claimed.
    3. Multi-Scenario & Calendar Integration: Evaluates upcoming renewal spikes, lump-sum annual outlays,
       revenue-to-software commitment ratios, and projected liquidity shortfalls.
    4. Cautious & Non-Destructive: Never recommends automatic cancellation based solely on high cost.
       Cancellation is strictly reserved for verified zombie discretionary tools in Tier 3.
    5. Insufficient Data Protection: Returns empty or cautious review states when operating revenue
       or subscription history is insufficient. Projections and simulations are explicitly disclosed.
    """

    NON_OPERATING_KEYWORDS = [
        "initial balance", "account funding", "balance adjustment", "general funding",
        "deposit", "bank transfer", "wallet funding", "reserve deposit", "top up",
        "reversal", "adjustment", "paypal balance", "subwise",
        "currency conversion", "conversion leg", "exchange rate", "paypal transaction", "paypal transfer"
    ]

    @classmethod
    def is_non_operating(cls, tx: Transaction) -> bool:
        desc = (tx.raw_description or "").lower()
        vendor = (tx.normalized_vendor or "").lower()
        cat = (tx.category or "").lower()
        return any(kw in desc or kw in vendor or kw in cat for kw in cls.NON_OPERATING_KEYWORDS)

    @classmethod
    def generate_recommendations(
        cls,
        business: BusinessProfile,
        subscriptions: List[Subscription],
        transactions: Optional[List[Transaction]] = None
    ) -> List[Recommendation]:
        """
        Generates actionable, evidence-backed optimization and risk recommendations.
        Combines historical spending audits with calendar-aware forward forecast intelligence.
        """
        if not subscriptions:
            return []

        active_subs = [s for s in subscriptions if s.status != "cancelled"]
        if not active_subs:
            return []

        tx_list = transactions or []
        operating_txs = [tx for tx in tx_list if not cls.is_non_operating(tx)]

        # Operating revenue calculation
        operating_revenue = sum(float(tx.gross_amount) for tx in operating_txs if tx.gross_amount > 0)

        # Compute monthly cadence equivalents for each sub
        sub_commitments: Dict[int, Dict[str, float]] = {}
        for s in active_subs:
            m_eq, a_eq = SubscriptionExpenseAnalyzer.calculate_cadence_equivalents(s.latest_amount, s.cadence)
            sub_commitments[s.id] = {"monthly": m_eq, "annual": a_eq}

        total_monthly_commit = sum(v["monthly"] for v in sub_commitments.values())

        # Generate forecast intelligence for forward calendar analysis
        forecast = ForecastEngine.generate_forecast(business, subscriptions, tx_list, forecast_months=6)
        forecast_status = forecast.get("status", "insufficient_data")
        payment_calendar = forecast.get("payment_calendar", [])
        monthly_scheduled_totals = forecast.get("monthly_scheduled_subscription_totals", [])
        upcoming_payments = forecast.get("upcoming_subscription_payments", [])
        forecast_timeline = forecast.get("forecast") or forecast.get("forecast_timeline", [])
        has_verified_cash = forecast.get("has_verified_cash", False)
        verified_starting_cash = forecast.get("verified_starting_cash") or 0.0

        recommendations: List[Recommendation] = []
        vendor_rec_count: Dict[str, int] = {}

        def add_rec(rec: Recommendation):
            v = rec.vendor_name or "General"
            # Allow multiple for portfolio alerts or distinct action types
            if v != "Portfolio" and vendor_rec_count.get(v, 0) >= 1 and rec.action_type not in ("CONSOLIDATE", "RENEWAL_RISK"):
                return
            vendor_rec_count[v] = vendor_rec_count.get(v, 0) + 1
            recommendations.append(rec)

        # -------------------------------------------------------------
        # 1. REVENUE-BASED AUDIT RECOMMENDATION
        # -------------------------------------------------------------
        if operating_revenue > 0:
            sub_rev_ratio = total_monthly_commit / operating_revenue
            if sub_rev_ratio >= 0.25:
                pct_str = f"{sub_rev_ratio * 100:.1f}%"
                discretionary_spend = sum(
                    sub_commitments[s.id]["monthly"] for s in active_subs if s.priority_tier == 3
                )
                potential_save = round(min(discretionary_spend, total_monthly_commit * 0.20), 2)
                if potential_save == 0:
                    potential_save = round(total_monthly_commit * 0.15, 2)

                add_rec(Recommendation(
                    business_id=business.id,
                    subscription_id=None,
                    vendor_name="Portfolio",
                    action_type="REVENUE_AUDIT",
                    title="Audit Software Overhead Against Operating Revenue",
                    identified_issue=f"High Subscription Burden: Software expenses consume {pct_str} of monthly operating revenue.",
                    supporting_evidence=(
                        f"Monthly software commitments total ${total_monthly_commit:.2f}/mo against verified operating "
                        f"revenue of ${operating_revenue:.2f}. Standard fintech guidance recommends keeping software below 15-20%."
                    ),
                    confidence="high",
                    explanation="Generated because verified operating sales are known and subscription outlays exceed the 25% risk threshold.",
                    rationale=(
                        f"Software commitments currently represent {pct_str} of top-line operating inflows. "
                        f"In an economic downturn or sales contraction, fixed recurring software overhead rapidly depletes cash reserves."
                    ),
                    action_plan=(
                        "1. Implement an immediate SaaS acquisition freeze.\n"
                        "2. Audit all Tier 3 (Discretionary) subscriptions for unused team seats.\n"
                        "3. Consolidate overlapping collaboration and productivity tools."
                    ),
                    potential_monthly_saving=potential_save,
                    potential_annual_saving=round(potential_save * 12.0, 2),
                    runway_impact_days=max(14, int((potential_save * 12.0 / max(1000.0, operating_revenue * 0.3)) * 30)),
                    status="pending"
                ))

        # -------------------------------------------------------------
        # 2. PRICE CREEP & RATE INCREASE ALERTS
        # -------------------------------------------------------------
        for sub in active_subs:
            pct = float(sub.price_change_pct or 0.0)
            is_var = getattr(sub, "billing_type", "fixed") == "variable"
            det_type = getattr(sub, "detection_type", "confirmed")

            if pct >= 10.0 and not is_var and det_type == "confirmed":
                creep_diff = round(sub.latest_amount - sub.average_amount, 2)
                annual_diff = round(creep_diff * 12.0, 2)

                script = (
                    f"Hello {sub.vendor_name} Billing Team,\n\n"
                    f"Our finance team at {business.company_name} noticed that our recurring invoice climbed by {pct:+.1f}% "
                    f"from ${sub.average_amount:.2f} to ${sub.latest_amount:.2f}.\n"
                    f"As part of our internal cost control audit, we would like to review our active seats and request a rate lock "
                    f"at our previous baseline agreement or transition to an optimized tier.\n\n"
                    f"Best regards,\nFinance & Operations"
                )

                add_rec(Recommendation(
                    business_id=business.id,
                    subscription_id=sub.id,
                    vendor_name=sub.vendor_name,
                    action_type="RENEGOTIATE",
                    title=f"Renegotiate Rate Lock & Audit Seats for {sub.vendor_name}",
                    identified_issue=f"Price Creep: Recurring charge climbed by +{pct:.1f}% over historical cycles.",
                    supporting_evidence=(
                        f"Initial average charge was ${sub.average_amount:.2f}; latest cycle billed at ${sub.latest_amount:.2f}. "
                        f"Represents an unbudgeted monthly escalation of ${creep_diff:.2f}."
                    ),
                    confidence="high" if pct >= 15.0 else "medium",
                    explanation=f"Generated from transaction history tracking payment escalation across multiple billing cycles for {sub.vendor_name}.",
                    rationale=(
                        f"{sub.vendor_name} fees expanded by +{pct:.1f}%. Unmonitored price creep is a leading cause of silent SaaS budget expansion. "
                        f"Suppliers typically reverse unannounced price hikes or offer legacy pricing upon formal query."
                    ),
                    action_plan="Send rate review query to vendor account manager and audit member access logs to reclaim inactive seat licenses.",
                    potential_monthly_saving=max(25.0, creep_diff),
                    potential_annual_saving=max(300.0, annual_diff),
                    runway_impact_days=10,
                    negotiation_script=script,
                    status="pending"
                ))

        # -------------------------------------------------------------
        # 3. REDUNDANT SUBSCRIPTION & FUNCTIONAL OVERLAP DETECTION
        # -------------------------------------------------------------
        group_map: Dict[str, List[Subscription]] = {}
        for sub in active_subs:
            if sub.redundancy_group:
                group_map.setdefault(sub.redundancy_group, []).append(sub)

        for group_name, subs in group_map.items():
            if len(subs) > 1:
                subs_sorted = sorted(subs, key=lambda s: sub_commitments[s.id]["monthly"], reverse=True)
                primary_sub = subs_sorted[0]
                secondary_subs = subs_sorted[1:]

                for sec_sub in secondary_subs:
                    sec_monthly = sub_commitments[sec_sub.id]["monthly"]
                    sec_annual = sub_commitments[sec_sub.id]["annual"]

                    add_rec(Recommendation(
                        business_id=business.id,
                        subscription_id=sec_sub.id,
                        vendor_name=sec_sub.vendor_name,
                        action_type="CONSOLIDATE",
                        title=f"Review Overlap: {sec_sub.vendor_name} and {primary_sub.vendor_name}",
                        identified_issue=(
                            f"Overlapping Functionality in '{SubscriptionExpenseAnalyzer.standardize_category(sec_sub.category)}'. "
                            f"Multiple subscriptions detected for {group_name.replace('_', ' ')}."
                        ),
                        supporting_evidence=(
                            f"Both {primary_sub.vendor_name} (${sub_commitments[primary_sub.id]['monthly']:.2f}/mo) and "
                            f"{sec_sub.vendor_name} (${sec_monthly:.2f}/mo) are active in your ledger. "
                            f"Combined monthly commitment: ${(sub_commitments[primary_sub.id]['monthly'] + sec_monthly):.2f}/mo."
                        ),
                        confidence="medium",
                        explanation="Generated because multiple active subscriptions share the same functional redundancy group.",
                        rationale=(
                            f"Both tools provide overlapping capabilities. Standardizing team workflows on a single platform "
                            f"eliminates redundant licensing fees and improves cross-functional productivity."
                        ),
                        action_plan=(
                            f"1. Conduct user survey to determine team utilization between {sec_sub.vendor_name} and {primary_sub.vendor_name}.\n"
                            f"2. Transition active projects and users onto the preferred tool.\n"
                            f"3. Do not renew {sec_sub.vendor_name} at the end of the current billing cycle."
                        ),
                        potential_monthly_saving=round(sec_monthly, 2),
                        potential_annual_saving=round(sec_annual, 2),
                        runway_impact_days=max(7, int((sec_annual / max(1000.0, operating_revenue * 0.3 if operating_revenue > 0 else 2500.0)) * 30)),
                        status="pending"
                    ))

        # -------------------------------------------------------------
        # 4. HIGH-COST EXPENSIVE SUBSCRIPTION REVIEW
        # -------------------------------------------------------------
        for sub in active_subs:
            m_eq = sub_commitments[sub.id]["monthly"]
            if m_eq >= 120.0:
                plan_audit_save = round(m_eq * 0.25, 2)
                add_rec(Recommendation(
                    business_id=business.id,
                    subscription_id=sub.id,
                    vendor_name=sub.vendor_name,
                    action_type="REVIEW",
                    title=f"Review High-Cost Plan Tier for {sub.vendor_name}",
                    identified_issue=f"High Monthly Expenditure: ${m_eq:.2f}/mo commitment (${sub_commitments[sub.id]['annual']:.2f}/yr).",
                    supporting_evidence=(
                        f"Current billing: ${sub.latest_amount:.2f} ({sub.cadence}). "
                        f"This provider accounts for a substantial share of total SaaS outlays."
                    ),
                    confidence="high" if m_eq >= 200.0 else "medium",
                    explanation=f"Generated because {sub.vendor_name} is one of the highest-cost subscriptions in your operating software stack.",
                    rationale=(
                        f"{sub.vendor_name} is a high-commitment provider. For high-cost software, suppliers often maintain unadvertised "
                        f"mid-tier plans or volume tiers that deliver core features at 20-30% lower cost."
                    ),
                    action_plan=(
                        f"1. Audit user seat utilization in {sub.vendor_name} admin console.\n"
                        f"2. Check if team is utilizing enterprise features or if a standard plan suffices.\n"
                        f"3. Inquire with sales representative regarding upcoming renewal promotions."
                    ),
                    potential_monthly_saving=plan_audit_save,
                    potential_annual_saving=round(plan_audit_save * 12.0, 2),
                    runway_impact_days=8,
                    status="pending"
                ))

        # -------------------------------------------------------------
        # 5. ANNUAL DISCOUNT CONVERSION FOR MISSION-CRITICAL (TIER 1)
        # -------------------------------------------------------------
        for sub in active_subs:
            m_eq = sub_commitments[sub.id]["monthly"]
            if sub.priority_tier == 1 and sub.cadence == "monthly" and m_eq >= 35.0:
                annual_discount_save = round(m_eq * 0.18, 2)
                add_rec(Recommendation(
                    business_id=business.id,
                    subscription_id=sub.id,
                    vendor_name=sub.vendor_name,
                    action_type="SWITCH_ANNUAL",
                    title=f"Switch {sub.vendor_name} to Annual Pre-Pay Discount",
                    identified_issue="Mission-critical service billed on monthly retail rate without annual discount.",
                    supporting_evidence=(
                        f"Billed monthly at ${sub.latest_amount:.2f}/mo. Since {sub.vendor_name} is essential infrastructure, "
                        f"monthly retail billing results in unnecessary 15-25% premiums over annual commitments."
                    ),
                    confidence="high",
                    explanation="Generated because Tier 1 tools have proven long-term retention, qualifying for enterprise annual discounting.",
                    rationale=(
                        f"Because {sub.vendor_name} is mission-critical to ongoing operations, cancellation is not advisable. "
                        f"Switching from monthly billing to annual billing typically yields an immediate 15% to 20% cost reduction."
                    ),
                    action_plan=f"Request annual contract invoicing from {sub.vendor_name} customer success to lock in discount rate.",
                    potential_monthly_saving=annual_discount_save,
                    potential_annual_saving=round(annual_discount_save * 12.0, 2),
                    runway_impact_days=6,
                    status="pending"
                ))

        # -------------------------------------------------------------
        # 6. EVIDENCE-BASED CANCELLATION FOR INACTIVE / ZOMBIE DISCRETIONARY TOOLS
        # -------------------------------------------------------------
        for sub in active_subs:
            if sub.status == "zombie" and sub.priority_tier == 3:
                m_eq = sub_commitments[sub.id]["monthly"]
                add_rec(Recommendation(
                    business_id=business.id,
                    subscription_id=sub.id,
                    vendor_name=sub.vendor_name,
                    action_type="CANCEL",
                    title=f"Consider Cancelling Inactive Tool: {sub.vendor_name}",
                    identified_issue="Verified Inactive: Classified as zombie discretionary software with no ongoing operational utility.",
                    supporting_evidence=(
                        f"Classified as Tier 3 (Discretionary). "
                        f"Recurring drain of ${sub.latest_amount:.2f} ({sub.cadence}) detected without active operational reliance."
                    ),
                    confidence="high",
                    explanation="Generated solely because the subscription is verified as an inactive zombie tool in Tier 3.",
                    rationale=(
                        f"{sub.vendor_name} has been classified as an inactive zombie tool with zero mission-critical dependencies. "
                        f"Decommissioning this subscription immediately stops recurring cash leaks."
                    ),
                    action_plan="Verify that no active team exports or integrations depend on the account, then cancel renewal in PayPal.",
                    potential_monthly_saving=round(m_eq, 2),
                    potential_annual_saving=round(sub_commitments[sub.id]["annual"], 2),
                    runway_impact_days=max(8, int((sub_commitments[sub.id]["annual"] / 2500.0) * 30)),
                    status="pending"
                ))

        # -------------------------------------------------------------
        # 7. POTENTIAL (UNCONFIRMED) SUBSCRIPTION CAUTIOUS REVIEW
        # -------------------------------------------------------------
        for sub in active_subs:
            det_type = getattr(sub, "detection_type", "confirmed")
            if det_type == "potential":
                m_eq = sub_commitments[sub.id]["monthly"]
                add_rec(Recommendation(
                    business_id=business.id,
                    subscription_id=sub.id,
                    vendor_name=sub.vendor_name,
                    action_type="REVIEW",
                    title=f"Verify Trial / Ongoing Usage for {sub.vendor_name}",
                    identified_issue="Potential Subscription: Single payment detected for recognized SaaS provider.",
                    supporting_evidence=(
                        f"Detected initial payment of ${sub.latest_amount:.2f}. Awaiting second billing cycle "
                        f"to confirm whether this is an ongoing recurring commitment."
                    ),
                    confidence="low",
                    explanation="Generated because this is a first-time payment to a recognized SaaS vendor, requiring team verification.",
                    rationale=(
                        f"A single disbursement to {sub.vendor_name} was detected. Many software trials auto-renew into expensive "
                        f"annual or monthly commitments if not actively evaluated by the purchaser."
                    ),
                    action_plan="Confirm with team members whether this purchase was a one-time service or an ongoing trial to retain.",
                    potential_monthly_saving=round(m_eq * 0.5, 2),
                    potential_annual_saving=round(m_eq * 6.0, 2),
                    runway_impact_days=3,
                    status="pending"
                ))

        # -------------------------------------------------------------
        # 8. CALENDAR-AWARE: APPROACHING LARGE ANNUAL RENEWALS
        # -------------------------------------------------------------
        # Identify confirmed annual subscriptions renewing in Months 1 or 2
        for pmt in upcoming_payments:
            pmt_cadence = (pmt.get("billing_frequency") or pmt.get("cadence") or "").lower()
            pmt_amt = float(pmt.get("expected_payment_amount") or pmt.get("expected_amount") or 0.0)
            if (
                pmt.get("detection_type") == "confirmed"
                and pmt_cadence == "annual"
                and pmt_amt >= 150.0
            ):
                v_name = pmt.get("vendor_name", "Vendor")
                amt = pmt_amt
                due_date = pmt.get("expected_payment_date", "Upcoming")
                rev_ratio_note = ""
                if operating_revenue > 0:
                    ratio = (amt / operating_revenue) * 100.0
                    rev_ratio_note = f" (consumes {ratio:.1f}% of historical monthly operating revenue)"

                add_rec(Recommendation(
                    business_id=business.id,
                    subscription_id=pmt.get("subscription_id"),
                    vendor_name=v_name,
                    action_type="RENEWAL_RISK",
                    title=f"Prepare Cash Buffer for Approaching Annual Renewal: {v_name}",
                    identified_issue=f"Large Annual Renewal Due Soon: Lump-sum commitment of ${amt:.2f} due on {due_date}{rev_ratio_note}.",
                    supporting_evidence=(
                        f"Verified contractual renewal for {v_name} scheduled on {due_date}. "
                        f"Annual cadence requires an immediate single-day disbursement of ${amt:.2f}."
                    ),
                    confidence="high",
                    explanation=f"Generated from calendar-aware renewal scheduling tracking approaching annual milestones for {v_name}.",
                    rationale=(
                        f"Approaching annual renewals represent lump-sum liquidity events. Without advance cash ring-fencing, "
                        f"large annual debits risk triggering unexpected overdrafts or working capital crunches."
                    ),
                    action_plan=(
                        f"1. Audit team license utilization for {v_name} before {due_date} to reclaim unused seats.\n"
                        f"2. Ensure liquid reserves of at least ${amt:.2f} are set aside.\n"
                        f"3. Inquire with supplier whether semi-annual or quarterly billing is available if cash preservation is preferred."
                    ),
                    potential_monthly_saving=round(amt * 0.10 / 12.0, 2),
                    potential_annual_saving=round(amt * 0.10, 2),
                    runway_impact_days=5,
                    status="pending"
                ))

        # -------------------------------------------------------------
        # 9. CALENDAR-AWARE: MULTI-SUBSCRIPTION RENEWAL CONCENTRATION
        # -------------------------------------------------------------
        for m_tot in monthly_scheduled_totals:
            c_count = m_tot.get("confirmed_renewals_count", 0)
            c_amt = m_tot.get("total_confirmed_amount", 0.0)
            m_name = m_tot.get("month_name", "Upcoming Month")
            is_high = m_tot.get("is_high_concentration", False)

            # Check if 2+ subscriptions renew in the same month with significant volume
            if c_count >= 2 and (is_high or c_amt >= 200.0):
                # Find vendors renewing in this month
                m_idx = m_tot.get("month_index")
                vendors_in_month = [
                    p.get("vendor_name") for p in payment_calendar
                    if p.get("month_index") == m_idx and p.get("detection_type") == "confirmed"
                ]
                v_str = ", ".join(vendors_in_month[:3])

                add_rec(Recommendation(
                    business_id=business.id,
                    subscription_id=None,
                    vendor_name="Portfolio",
                    action_type="RENEWAL_RISK",
                    title=f"Stagger Subscription Renewal Concentration in {m_name}",
                    identified_issue=(
                        f"Renewal Clustering: {c_count} subscriptions renew in {m_name}, "
                        f"concentrating ${c_amt:.2f} in outflows."
                    ),
                    supporting_evidence=(
                        f"{c_count} confirmed renewals ({v_str}) coincide in {m_name}, totalling ${c_amt:.2f}."
                        + (f" Consumes {m_tot.get('revenue_commitment_pct', 0):.1f}% of projected revenue." if operating_revenue > 0 else "")
                    ),
                    confidence="high" if operating_revenue > 0 else "medium",
                    explanation=f"Generated because multiple confirmed subscriptions renew in {m_name}, creating an outflow spike.",
                    rationale=(
                        f"Concentrated renewal dates create artificial cash volatility. Spreading renewals across alternate months "
                        f"or shifting billing anchor dates smooths working capital requirements."
                    ),
                    action_plan=(
                        f"1. Contact account managers for {v_str} to shift billing dates to an alternate billing window.\n"
                        f"2. Align large contract renewal dates with expected customer receivables."
                    ),
                    potential_monthly_saving=0.0,
                    potential_annual_saving=0.0,
                    runway_impact_days=4,
                    status="pending"
                ))

        # -------------------------------------------------------------
        # 10. CASH-FLOW PROTECTION: PROJECTED SHORTFALL OR CASH DEPLETION
        # -------------------------------------------------------------
        if forecast_status != "insufficient_data" and has_verified_cash:
            for pt in forecast_timeline:
                bal = pt.get("projected_closing_cash_balance", 0.0)
                is_depleted = pt.get("is_cash_depleted", False)
                m_name = pt.get("month_name", "Forward Month")
                m_idx = pt.get("month")

                if is_depleted or bal <= 0:
                    add_rec(Recommendation(
                        business_id=business.id,
                        subscription_id=None,
                        vendor_name="Portfolio",
                        action_type="CASHFLOW_PROTECTION",
                        title=f"Protect Cash Reserves: Liquidity Deficit Projected in {m_name}",
                        identified_issue=f"Projected Liquidity Deficit: Closing cash balance drops to ${bal:.2f} in Month {m_idx} ({m_name}).",
                        supporting_evidence=(
                            f"Verified starting cash is ${verified_starting_cash:.2f}. "
                            f"Combined operating outlays and subscription commitments exceed revenue, depleting reserves in {m_name}."
                        ),
                        confidence="high",
                        explanation="Generated because calendar-integrated cash-flow projections model reserves falling to zero.",
                        rationale=(
                            f"Without cost intervention or revenue acceleration, projected disbursements will deplete reserves. "
                            f"Immediate software rationalization extends survival horizon."
                        ),
                        action_plan=(
                            "1. Immediately freeze all new software acquisition.\n"
                            "2. Decommission inactive Tier 3 discretionary software.\n"
                            "3. Request extended payment terms on essential infrastructure."
                        ),
                        potential_monthly_saving=round(total_monthly_commit * 0.25, 2),
                        potential_annual_saving=round(total_monthly_commit * 0.25 * 12.0, 2),
                        runway_impact_days=21,
                        status="pending"
                    ))
                    # Only add one shortfall alert for the earliest depleted month
                    break

        # -------------------------------------------------------------
        # 11. CASH-FLOW PROTECTION: SINGLE MONTH REVENUE OVER-COMMITMENT
        # -------------------------------------------------------------
        if operating_revenue > 0 and forecast_status != "insufficient_data":
            for m_tot in monthly_scheduled_totals:
                pct = m_tot.get("revenue_commitment_pct", 0.0)
                m_name = m_tot.get("month_name", "")
                c_amt = m_tot.get("total_confirmed_amount", 0.0)
                if pct >= 35.0:
                    add_rec(Recommendation(
                        business_id=business.id,
                        subscription_id=None,
                        vendor_name="Portfolio",
                        action_type="CASHFLOW_PROTECTION",
                        title=f"Excessive Subscription Commitment in {m_name} ({pct:.1f}% of Revenue)",
                        identified_issue=f"Disproportionate SaaS Burden: Contractual software in {m_name} accounts for {pct:.1f}% of projected revenue.",
                        supporting_evidence=(
                            f"Scheduled confirmed renewals total ${c_amt:.2f} against projected revenue of ${operating_revenue:.2f}/mo. "
                            f"Financial best practices recommend capping recurring tools at 15–20%."
                        ),
                        confidence="high",
                        explanation=f"Generated because scheduled commitments in {m_name} exceed 35% of verified operating sales.",
                        rationale=(
                            f"Allocating {pct:.1f}% of top-line receipts to software leaves insufficient buffer for operating payroll and marketing."
                        ),
                        action_plan=(
                            f"1. Audit subscriptions renewing in {m_name}.\n"
                            f"2. Downgrade non-essential user seats before the billing date.\n"
                            f"3. Negotiate vendor payment plans."
                        ),
                        potential_monthly_saving=round(c_amt * 0.20, 2),
                        potential_annual_saving=round(c_amt * 0.20 * 12.0, 2),
                        runway_impact_days=12,
                        status="pending"
                    ))
                    break

        # Sort recommendations descending by potential annual savings
        recommendations.sort(key=lambda r: float(r.potential_annual_saving or 0.0), reverse=True)
        return recommendations

    # -----------------------------------------------------------------
    # STAGE 4: SUBSCRIPTION PURCHASE DECISION SIMULATOR
    # -----------------------------------------------------------------
    @classmethod
    def simulate_purchase(
        cls,
        business: BusinessProfile,
        subscriptions: List[Subscription],
        transactions: List[Transaction],
        request: PurchaseSimulationRequest
    ) -> PurchaseSimulationResponse:
        """
        Evaluates the prospective cash-flow impact, monthly equivalent cost,
        annual cost, renewal concentration, and liquidity solvency for a proposed purchase.
        """
        proposed_vendor = request.proposed_vendor.strip()
        amount = max(0.0, float(request.amount))
        cadence = (request.cadence or "monthly").lower().strip()
        purpose = request.business_purpose
        verified_discount_pct = request.verified_annual_discount_pct

        # 1. Cost & Equivalents
        if cadence == "annual":
            annual_cost = round(amount, 2)
            monthly_equivalent = round(amount / 12.0, 2)
            immediate_cash = round(amount, 2)
        elif cadence == "quarterly":
            annual_cost = round(amount * 4.0, 2)
            monthly_equivalent = round(amount / 3.0, 2)
            immediate_cash = round(amount, 2)
        elif cadence == "weekly":
            annual_cost = round(amount * 52.0, 2)
            monthly_equivalent = round((amount * 52.0) / 12.0, 2)
            immediate_cash = round(amount, 2)
        else:  # monthly
            cadence = "monthly"
            monthly_equivalent = round(amount, 2)
            annual_cost = round(amount * 12.0, 2)
            immediate_cash = round(amount, 2)

        # 2. Annual vs Monthly Analysis
        if cadence == "monthly":
            monthly_pmt = amount
            if verified_discount_pct is not None and verified_discount_pct > 0:
                ann_pmt = round(amount * 12.0 * (1.0 - verified_discount_pct / 100.0), 2)
                ann_monthly = round(ann_pmt / 12.0, 2)
                has_verified_discount = True
                discount_disclosure = f"Verified discount of {verified_discount_pct:.1f}% applied based on user-supplied terms. Annual contract total: ${ann_pmt:.2f}."
            else:
                ann_pmt = round(amount * 12.0, 2)
                ann_monthly = round(amount, 2)
                has_verified_discount = False
                discount_disclosure = (
                    "No verified annual discount supplied. Retail price extrapolated at 12x monthly rate ($0 discount). "
                    "Never assume an annual discount is guaranteed until verified with the supplier."
                )

            immediate_diff = round(ann_pmt - monthly_pmt, 2)
            impact_closing = (
                f"Selecting annual upfront billing requires ${immediate_diff:.2f} more immediate cash out of reserves in Month 1, "
                f"but saves ongoing monthly disbursements for the subsequent 11 months."
            )
        else:  # annual or other
            ann_pmt = annual_cost
            ann_monthly = monthly_equivalent
            monthly_pmt = monthly_equivalent
            has_verified_discount = verified_discount_pct is not None and verified_discount_pct > 0
            if has_verified_discount:
                discount_disclosure = f"Annual contract includes verified discount of {verified_discount_pct:.1f}%."
            else:
                discount_disclosure = "Annual contract evaluated. Standard monthly retail rates may vary without verified supplier agreement."

            immediate_diff = round(ann_pmt - monthly_pmt, 2)
            impact_closing = (
                f"Paying annually incurs an upfront cash reduction of ${ann_pmt:.2f} immediately, "
                f"versus spread monthly outlays of ${monthly_pmt:.2f}/mo."
            )

        annual_vs_monthly = AnnualVsMonthlyComparison(
            monthly_payment_amount=round(monthly_pmt, 2),
            annual_payment_amount=round(ann_pmt, 2),
            annualized_monthly_cost=round(ann_monthly, 2),
            discount_pct=verified_discount_pct if has_verified_discount else None,
            has_verified_discount=has_verified_discount,
            discount_disclosure=discount_disclosure,
            immediate_cash_outflow_difference=immediate_diff,
            impact_on_projected_closing_balance=impact_closing,
        )

        # 3. Forecast Baseline Integration
        forecast = ForecastEngine.generate_forecast(business, subscriptions, transactions, forecast_months=6)
        status = forecast.get("status", "insufficient_data")
        hist_rev = forecast.get("historical_monthly_operating_revenue", 0.0)
        hist_non_sub = forecast.get("historical_monthly_non_sub_expenses", 0.0)
        hist_sub = forecast.get("confirmed_monthly_subscription_commitments", 0.0)
        verified_starting_cash = forecast.get("verified_starting_cash")
        has_verified_cash = forecast.get("has_verified_cash", False)
        starting_cash = verified_starting_cash if (has_verified_cash and verified_starting_cash is not None) else 0.0

        current_monthly_burn = round(hist_non_sub + hist_sub, 2)
        simulated_monthly_burn = round(current_monthly_burn + monthly_equivalent, 2)

        # 4. 6-Month Timeline Simulation
        baseline_timeline = forecast.get("forecast") or forecast.get("forecast_timeline", [])
        timeline_comparison: List[MonthProjectionPoint] = []
        running_sim_cash = starting_cash
        simulated_lowest_balance: Optional[float] = None
        current_lowest_balance: Optional[float] = None
        shortfall_detected = False
        shortfall_month: Optional[str] = None

        for idx, base_pt in enumerate(baseline_timeline):
            m = base_pt.get("month", idx + 1)
            m_name = base_pt.get("month_name", f"Month {m}")
            base_bal = base_pt.get("projected_closing_cash_balance")

            if base_bal is not None:
                if current_lowest_balance is None or base_bal < current_lowest_balance:
                    current_lowest_balance = base_bal

            # Calculate proposed outflow in this month
            if cadence == "annual":
                # Incurred in Month 1
                proposed_outflow = amount if m == 1 else 0.0
            elif cadence == "quarterly":
                # Incurred in Months 1 and 4
                proposed_outflow = amount if m in (1, 4) else 0.0
            else:  # monthly or weekly equivalent
                proposed_outflow = monthly_equivalent

            # Net flow with proposed outflow
            base_net = base_pt.get("projected_net_cashflow", 0.0)
            sim_net = base_net - proposed_outflow
            running_sim_cash += sim_net

            sim_bal = round(running_sim_cash, 2)
            if simulated_lowest_balance is None or sim_bal < simulated_lowest_balance:
                simulated_lowest_balance = sim_bal

            is_depleted = sim_bal <= 0 and has_verified_cash and starting_cash > 0
            if (sim_bal < 0 or is_depleted) and not shortfall_detected:
                shortfall_detected = True
                shortfall_month = m_name

            timeline_comparison.append(MonthProjectionPoint(
                month=m,
                month_name=m_name,
                baseline_closing_balance=base_bal,
                simulated_closing_balance=sim_bal if has_verified_cash else None,
                proposed_outflow=round(proposed_outflow, 2),
                is_cash_depleted=is_depleted,
            ))

        # 5. Renewal Concentration Evaluation
        m1_totals = forecast.get("monthly_scheduled_subscription_totals", [])
        first_month_tot = m1_totals[0] if len(m1_totals) > 0 else {}
        if first_month_tot.get("is_high_concentration", False):
            renewal_concentration_effect = (
                f"Caution: Month 1 ({first_month_tot.get('month_name', '')}) already contains high renewal obligations. "
                f"Adding ${immediate_cash:.2f} exacerbates short-term liquidity concentration."
            )
        elif cadence == "annual":
            renewal_concentration_effect = (
                f"Creates a single-month lump-sum obligation of ${immediate_cash:.2f} in Month 1. "
                f"Subsequent months experience no recurring outlay from this vendor."
            )
        else:
            renewal_concentration_effect = (
                f"Distributes ${monthly_equivalent:.2f}/mo evenly across the 6-month projection horizon "
                f"without introducing single-day renewal spikes."
            )

        # 6. Verdict Determination
        action_advice: List[str] = []

        if status == "insufficient_data":
            verdict = "Insufficient financial data"
            verdict_badge = "neutral"
            verdict_explanation = (
                "Cannot definitively evaluate affordability because your connected PayPal Sandbox account "
                "currently lacks verified completed operating revenue transactions and verified starting cash. "
                "The figures below demonstrate the mathematical impact under a hypothetical simulation."
            )
            action_advice = [
                "Synchronize verified operating transactions from PayPal to establish a real revenue baseline.",
                "Verify your current business starting cash balance in settings.",
                "Review the proposed contract for cancellation notice periods before signing.",
            ]
        elif shortfall_detected or (simulated_lowest_balance is not None and simulated_lowest_balance < 0):
            verdict = "Consider postponing"
            verdict_badge = "danger"
            verdict_explanation = (
                f"Postponing recommended. Adding {proposed_vendor} is projected to cause a cash-flow shortfall "
                f"in {shortfall_month or 'the projection period'}, with closing cash dropping to "
                f"${(simulated_lowest_balance or 0.0):.2f}."
            )
            action_advice = [
                f"Defer acquiring {proposed_vendor} until operating revenue expands or existing software is retired.",
                "If acquiring immediately is critical, negotiate monthly or delayed-billing terms instead of upfront commitments.",
                "Audit discretionary Tier 3 subscriptions to identify offsetting savings before purchase.",
            ]
        else:
            # Check revenue burden ratio
            total_future_sub_monthly = hist_sub + monthly_equivalent
            future_sub_ratio = (total_future_sub_monthly / hist_rev) if hist_rev > 0 else 0.0

            if future_sub_ratio >= 0.25 or (
                simulated_lowest_balance is not None and simulated_lowest_balance < (current_monthly_burn * 0.5)
            ):
                verdict = "Affordable with caution"
                verdict_badge = "warning"
                verdict_explanation = (
                    f"Affordable with caution. Projected cash reserves remain positive (lowest point: "
                    f"${(simulated_lowest_balance or 0.0):.2f}), but total subscription overhead will reach "
                    f"{future_sub_ratio * 100:.1f}% of monthly operating revenue (above the 20% safe ceiling)."
                )
                action_advice = [
                    f"Request a 14-day or 30-day proof-of-concept trial with {proposed_vendor} before contracting.",
                    f"Confirm team seat requirements to avoid licensing unneeded users.",
                    "Set an explicit 90-day review checkpoint to measure software ROI against operating goals.",
                ]
            else:
                verdict = "Affordable under current assumptions"
                verdict_badge = "success"
                verdict_explanation = (
                    f"Affordable under current assumptions. Projected cash balance remains resilient "
                    f"(lowest projected point: ${(simulated_lowest_balance or 0.0):.2f}) and recurring commitments "
                    f"remain within healthy operating thresholds ({future_sub_ratio * 100:.1f}% of revenue)."
                )
                action_advice = [
                    f"Proceed with {proposed_vendor} purchase in accordance with standard procurement policy.",
                    "Inquire whether an annual pre-pay discount is available if long-term utility is verified.",
                    "Log renewal notice date into your financial calendar 30 days prior to contract rollover.",
                ]

        return PurchaseSimulationResponse(
            proposed_vendor=proposed_vendor,
            amount=amount,
            cadence=cadence,
            business_purpose=purpose,
            verdict=verdict,
            verdict_badge=verdict_badge,
            verdict_explanation=verdict_explanation,
            immediate_cash_impact=immediate_cash,
            monthly_equivalent_cost=monthly_equivalent,
            annual_cost=annual_cost,
            projected_shortfall_detected=shortfall_detected,
            shortfall_month=shortfall_month,
            renewal_concentration_effect=renewal_concentration_effect,
            current_monthly_burn=current_monthly_burn,
            simulated_monthly_burn=simulated_monthly_burn,
            current_lowest_balance=current_lowest_balance,
            simulated_lowest_balance=simulated_lowest_balance,
            annual_vs_monthly=annual_vs_monthly,
            timeline_comparison=timeline_comparison,
            action_advice=action_advice,
            confidence="high" if status in ("sufficient_data", "limited_data") else "low",
            is_hypothetical_simulation=True,
            simulation_methodology_note=(
                "Purchase simulation evaluates marginal cash impact on top of verified PayPal operating baseline "
                "and scheduled subscription obligations. Projections do not fabricate revenue or modify actual ledger transactions. "
                "Discounts are applied only when explicitly verified by user input."
            ),
        )
